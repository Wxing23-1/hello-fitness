/// 常见食物营养库
///
/// 数据参考《中国食物成分表（第6版）》，按每 100 克可食部计。
/// 覆盖日常中餐常见食材和成品，够日常记录用。
///
/// 为什么内置而不是调接口：
/// 查营养成分是记录饮食最频繁的操作，走网络会慢且断网就不能用。
/// 这份表不大（约 90 条），内置进包里换来即时响应和离线可用。
/// 用户吃到表里没有的东西，可以自己添加（存进 Hive）或用 AI 估算。
class FoodDatabase {
  /// 全部内置食物
  static List<FoodItem> getAll() => [
        ..._staples(),
        ..._proteins(),
        ..._vegetables(),
        ..._fruits(),
        ..._nuts(),
        ..._drinks(),
        ..._snacks(),
      ];

  /// 按 id 查，找不到返回 null
  static FoodItem? getById(String id) {
    for (final f in getAll()) {
      if (f.id == id) return f;
    }
    return null;
  }

  /// 按分类筛选
  static List<FoodItem> getByCategory(FoodCategory category) {
    return getAll().where((f) => f.category == category).toList();
  }

  /// 按名称搜索
  ///
  /// 简单的子串匹配。食物名都是中文，不需要分词或拼音首字母
  static List<FoodItem> search(String keyword) {
    final k = keyword.trim();
    if (k.isEmpty) return getAll();

    return getAll().where((f) => f.name.contains(k)).toList();
  }

